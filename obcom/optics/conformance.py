"""Conformance vectors: the golden suite for any other traversal of the same graphs (the browser
visualizer's TypeScript ``sees``). Each vector is (components, proven state, environment) →
expected ``sees()`` per detector and expected ``check`` verdicts, generated by *this* solver from
the canonical jk15 sketch, a BESO-style fan-in branch, a selector-less TMMT and the red-team
edge cases. Divergence is a red CI, never a wrong drawing in the dome.

``optics-conformance [path]`` writes the suite as JSON (default ``optics_conformance.json``).
"""

