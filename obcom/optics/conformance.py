def build_vector(scenario: Scenario, registry: KindRegistry = DEFAULT_REGISTRY) -> ConformanceVector:
    graph = parse_graph(scenario.components, registry=registry)
    return ConformanceVector(
        name=scenario.name,
        description=scenario.description,
        components=dict(graph.components),
        state=dict(scenario.state.selectors),
        environment=scenario.state.environment,
        expected_sees={d: sorted(sees(graph, scenario.state, d), key=lambda r: (r.light_class, r.terminal, r.via)) for d in scenario.detectors},
        expected_checks=[check_result(graph, scenario.state, d, f) for d, f in scenario.checks],
    )


def build_suite(scenarios: Iterable[Scenario] = SCENARIOS, registry: KindRegistry = DEFAULT_REGISTRY) -> ConformanceSuite:
    return ConformanceSuite(generated_from=default_generator(), vectors=[build_vector(s, registry) for s in scenarios])


def render(suite: ConformanceSuite) -> str:
    return suite.model_dump_json(by_alias=True, exclude_none=True, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    out = Path(args[0]) if args else Path("optics_conformance.json")
    suite = build_suite()
    out.write_text(render(suite), encoding="utf-8")
    print(f"{len(suite.vectors)} conformance vectors -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
