@dataclass(frozen=True)
class Scenario:
    name: str
    description: str
    components: Mapping
    state: ProvenState
    detectors: tuple[str, ...]
    checks: tuple[tuple[str, str], ...] = field(default_factory=tuple)  #: (detector, function)


_JK15_NIGHT_POSITIONS = {"tertiary": "andor", "covercalibrator": "open", "covercalibrator.calibrator": "off", "dome": "open"}


def _jk15_night(*, moving=(), stale=(), **positions) -> ProvenState:
    """jk15 at astronomical night, imaging configuration, with position overrides."""
    return ProvenState.build({**_JK15_NIGHT_POSITIONS, **positions}, moving=moving, stale=stale, sun_alt_deg=-30.0, dome_shutter_open=True)


def _with_telemetry(state: ProvenState, key: str, telemetry: SelectorState) -> ProvenState:
    return ProvenState(selectors={**state.selectors, key: telemetry}, environment=state.environment, holds=state.holds)


